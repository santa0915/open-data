/**
 * ASCIIグリッドを構造化データに変換する。
 * 返り値の座標はすべてタイル座標(tx, ty)。ピクセル変換はゲーム層が行う。
 */
export function parseLevel(grid) {
  const rows = grid.length;
  const cols = grid[0].length;
  const solid = grid.map((row) => [...row].map((ch) => ch === '#'));
  const level = {
    cols,
    rows,
    solid,
    spawns: [],
    key: null,
    door: null,
    plates: [],
    gates: [],
    spikes: [],
  };

  for (let ty = 0; ty < rows; ty++) {
    for (let tx = 0; tx < cols; tx++) {
      const ch = grid[ty][tx];
      if (ch === '1') level.spawns[0] = { tx, ty };
      else if (ch === '2') level.spawns[1] = { tx, ty };
      else if (ch === 'K') level.key = { tx, ty };
      else if (ch === 'D') level.door = { tx, ty };
      else if (ch === 'P') level.plates.push({ tx, ty });
      else if (ch === 'G') level.gates.push({ tx, ty });
      else if (ch === 'S') level.spikes.push({ tx, ty });
    }
  }

  // ゲートは高速に引けるよう Set 化(closed 時に isSolid が参照する)
  level.gateSet = new Set(level.gates.map((g) => g.ty * cols + g.tx));
  return level;
}

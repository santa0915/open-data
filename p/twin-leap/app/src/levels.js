//
// レベル設計の不変条件(levels.test.mjs が機械検証する):
//   - 全行が同じ幅・外周がソリッド・スポーン2つ・ドア1つ
//   - ジャンプ到達高さとの関係: 2タイル段差=単独可 / 3タイル=積み重ね必須 /

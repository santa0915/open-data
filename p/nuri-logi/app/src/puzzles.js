// puzzles.js — パズルデータ(解答grid)とクルー導出
//
// クルーは保存しない(adr/0003 §2): 解答grid('#'=塗り '.'=空)からderiveClues
// が導出するため、手書きクルーと絵のズレという事故が構造的に起きない。
// テスト対象も「絵(grid)」1つで済む(puzzles.test.mjs)。
//
// 【工程B】PUZZLESは本番12問(5×5×3 + 10×10×6 + 15×15×3、game-design.md §5)。
// deriveClues/parsePuzzleおよびpuzzles.test.mjsは問数・サイズに依存しない
// 汎用実装(工程Aのプレースホルダ3問時代のまま変更していない)。

/**
 * 1本のライン('#'=塗り '.'=空の文字列)から連続塗りの長さ列(クルー)を導出する。
 * 空行は[0]を返す(表示は「0」。architecture.md §2)。
 * @param {string} line
 * @returns {number[]}
 */
function lineClue(line) {
  const runs = [];
  let count = 0;
  for (const ch of line) {
    if (ch === '#') {
      count += 1;
    } else {
      if (count > 0) runs.push(count);
      count = 0;
    }
  }
  if (count > 0) runs.push(count);
  return runs.length > 0 ? runs : [0];
}

/**
 * 解答gridから行・列のクルーを導出する。
 * @param {string[]} grid - 1行1文字列('#'/'.'のみ、矩形)
 * @returns {{rows: number[][], cols: number[][]}}
 */
export function deriveClues(grid) {
  const h = grid.length;
  const w = grid[0].length;

  const rows = grid.map((row) => lineClue(row));

  const cols = [];
  for (let x = 0; x < w; x++) {
    let col = '';
    for (let y = 0; y < h; y++) col += grid[y][x];
    cols.push(lineClue(col));
  }

  return { rows, cols };
}

/**
 * パズル定義({name, color, grid})を実行時表現に変換する。
 * @param {{name:string, color:string, grid:string[]}} p
 * @returns {{name:string, color:string, w:number, h:number,
 *            solution:Set<string>, clues:{rows:number[][], cols:number[][]}}}
 */
export function parsePuzzle(p) {
  const h = p.grid.length;
  const w = p.grid[0].length;
  const solution = new Set();

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (p.grid[y][x] === '#') solution.add(`${x},${y}`);
    }
  }

  return {
    name: p.name,
    color: p.color,
    w,
    h,
    solution,
    clues: deriveClues(p.grid),
  };
}


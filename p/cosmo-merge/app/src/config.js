// config.js — 全チューニング定数の一元管理
//
// ゲームの手触りに関わる数値はすべてこのファイルに集約する。
// 各値の意味と「変えると何が起きるか」は docs/development-guide.md の
// チューニング表を参照。コード側にマジックナンバーを散らさないこと。

/**
 * デフォルト設定を新しいオブジェクトとして返す。
 * テストや実験で部分的に上書きできるよう、共有定数ではなく
 * 毎回フレッシュなオブジェクトを生成する。
 */
export function defaultConfig() {
  return {
    // 盤面(プレイフィールド)の論理サイズ。単位はすべて論理ピクセル。
    board: {
      width: 440,
      height: 600,
      // ゲームオーバー判定ライン(盤面上端からのy座標)。
      // 天体の上端(y - r)がこのラインより上に居座るとゲームオーバー。
      deadlineY: 110,
      // 投下待機中の天体を保持するy座標。deadlineY より上に置く。
      dropY: 56,
    },

    physics: {
      gravity: 2200, // 重力加速度 [px/s^2]。大きいほどキビキビ落ちる
      airDrag: 0.06, // 空気抵抗(速度の線形減衰係数 [1/s])
      restitution: 0.12, // 反発係数(0=完全非弾性, 1=完全弾性)。跳ねすぎ注意
      contactFriction: 0.08, // 接触時の接線方向速度の減衰率(转がり抑制)
      groundFriction: 0.03, // 床接触時の水平速度減衰率(1ステップあたり)
      positionCorrection: 0.8, // めり込み解消の適用率(1.0で即時完全分離)
      solverIterations: 6, // 位置補正の反復回数。多いほど山が安定するが重い
      fixedDt: 1 / 120, // 物理の固定タイムステップ [s]。描画fpsとは独立
    },

    rules: {
      // 投下候補になる最大ティア(1始まり)。スイカ系の定石は下位5種のみ。
      spawnMaxTier: 5,
      // ティア1..spawnMaxTier の出現重み(正規化不要)
      spawnWeights: [22, 24, 22, 18, 14],
      // 投下後、次の投下が可能になるまでの秒数
      dropCooldown: 0.55,
      // 投下直後の天体をゲームオーバー判定から除外する猶予秒数
      gameOverGrace: 0.8,
      // デッドライン超えの継続がこの秒数に達したらゲームオーバー
      gameOverDelay: 1.0,
    },
  };
}

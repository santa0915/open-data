/**
 * ASCIIグリッドを構造化データに変換する。
 * 返り値の座標はすべて (x, y) のタイル座標で、キーは "x,y" 文字列。
 * @param {string[]} grid - 1行1文字列の配列
 * @returns {{cols:number, rows:number, walls:Set<string>, goals:Set<string>,
 *            boxes:Set<string>, player:{x:number,y:number}}}
 */
export function parseLevel(grid) {
  const rows = grid.length;
  const cols = grid[0].length;
  const walls = new Set();
  const goals = new Set();
  const boxes = new Set();
  let player = null;

  for (let y = 0; y < rows; y++) {
    const row = grid[y];
    for (let x = 0; x < cols; x++) {
      const ch = row[x];
      const k = `${x},${y}`;
      switch (ch) {
        case '#':
          walls.add(k);
          break;
        case '.':
          goals.add(k);
          break;
        case '$':
          boxes.add(k);
          break;
        case '*':
          goals.add(k);
          boxes.add(k);
          break;
        case '@':
          player = { x, y };
          break;
        case '+':
          goals.add(k);
          player = { x, y };
          break;
        default:
          // 床(半角スペース)や未知文字は障害物なしとして扱う
          break;
      }
    }
  }

  return { cols, rows, walls, goals, boxes, player };
}
